"""Configuration loading.

Precedence (highest first):
    1. ``PRINTQUOTA_*`` environment variables
    2. Values saved from the web console (``app_settings`` table), for the
       keys in :data:`RUNTIME_KEYS` only
    3. ``config/settings.yaml`` (path from ``PRINTQUOTA_CONFIG``)
    4. Built-in defaults in :data:`DEFAULTS`

Layer 2 is read through a provider that the database layer registers (see
:func:`register_override_provider`), so this module never imports the ORM.
Anything that decides how a process *reaches* the database or runs --
``database.*``, ``secret_key``, ``api.*``, ``logging.*`` and the CUPS paths
-- is deliberately not in :data:`RUNTIME_KEYS`: it stays file/env only and
is available through :func:`get_base_settings` without touching the
database.

Nothing operational is hardcoded at the call sites; every component reads
its values through :func:`get_settings`.
"""

